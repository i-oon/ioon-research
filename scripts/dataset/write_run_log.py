"""Write results/wm/RUNS.md from whatever checkpoints still exist.

`wm/runs/` is gitignored and each checkpoint is ~370 MB, so runs get deleted when the disk fills.
A run's configuration lives only inside its checkpoint, which means deleting one destroys the only
record of what it was -- nine run directories are already empty while their numbers are still
quoted in FINDINGS.md, and they can never be re-scored or even described.

Run this before deleting anything. It reads every checkpoint's stored config and writes a table
that survives the checkpoint.

  .venv/bin/python3 scripts/write_run_log.py
"""
import glob
import os
import sys

import torch

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCRIPTS = os.path.join(ROOT, "scripts")
sys.path.insert(0, ROOT)

BASE_FEMUR_M, BASE_TIBIA_M = 0.3429, 0.4139
FIELDS = ["action_lag", "lambda_cross", "lambda_adv", "cross_augment", "within_body_std",
          "md_head", "balance_embodiments", "ftm_embodiment_channel", "center_embeddings",
          "epochs", "batch_size", "lr", "seed"]


def geometry(body):
    try:
        femur = BASE_FEMUR_M * int(body[4:6]) / 10
        tibia = BASE_TIBIA_M * int(body[7:9]) / 10
        return f"{femur / tibia:.2f}", f"{abs(femur - tibia) * 1000:.0f}"
    except (ValueError, IndexError):
        return "-", "-"


def describe(path):
    ck = torch.load(path, map_location="cpu", weights_only=False)
    cfg = ck["config"]
    run = os.path.basename(os.path.dirname(path))
    checkpoints = sorted(os.path.basename(p) for p in
                         glob.glob(os.path.join(os.path.dirname(path), "*.pt")))
    settings = {k: cfg.get(k) for k in FIELDS if k in cfg}
    if cfg.get("sources"):
        scope = "cross-embodiment"
        data = ", ".join(cfg["sources"])
        bodies = f"held out: {list(cfg.get('heldout_bodies') or []) or 'none'}"
        if cfg.get("clips_per_body"):
            bodies += f" | capped: {list(cfg['clips_per_body'])}"
    else:
        scope = "single-morphology"
        data = cfg.get("data_dir", "?")
        held = cfg.get("heldout_morph", "")
        ratio, dead = geometry(held)
        train = " ".join(cfg.get("train_morphs", ()))
        bodies = f"train: {train} | held out: {held} (ratio {ratio}, dead zone {dead} mm)"
    return {"run": run, "epoch": ck.get("epoch", -1), "scope": scope, "data": data,
            "bodies": bodies, "settings": settings, "checkpoints": checkpoints}


def main():
    out = os.path.join(ROOT, "results", "wm", "RUNS.md")
    records = [describe(p) for p in sorted(glob.glob(os.path.join(ROOT, "wm/runs/*/best.pt")))]
    empty = sorted(os.path.basename(d.rstrip("/")) for d in glob.glob(os.path.join(ROOT, "wm/runs/*/"))
                   if not glob.glob(os.path.join(d, "*.pt")))

    lines = ["# Training runs",
             "",
             "Generated by `scripts/write_run_log.py` from the configs stored inside each",
             "checkpoint. `wm/runs/` is gitignored and checkpoints are ~370 MB each, so they get",
             "deleted when the disk fills -- and a run's config exists nowhere else. Regenerate",
             "this **before** deleting anything.",
             ""]
    for r in records:
        lines += [f"## {r['run']}", "",
                  f"- **{r['scope']}**, reached epoch {r['epoch']}",
                  f"- data: `{r['data']}`",
                  f"- {r['bodies']}",
                  f"- checkpoints on disk: {', '.join(r['checkpoints']) or 'none'}",
                  "- settings: " + ", ".join(f"`{k}={v}`" for k, v in r["settings"].items()),
                  ""]
    if empty:
        lines += ["## Deleted — config lost", "",
                  "These directories exist with no checkpoint, so nothing records what they were.",
                  "Numbers from them appear in FINDINGS.md and cannot be reproduced or re-scored.",
                  ""]
        lines += [f"- `{name}`" for name in empty] + [""]

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"-> {out}  ({len(records)} runs with checkpoints, {len(empty)} without)")


if __name__ == "__main__":
    main()
